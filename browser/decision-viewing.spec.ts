test('teaching links the card, recorded map targets and keyboard timeline without advancing inspection time', async ({ page }) => {
  await page.clock.install();
  await page.clock.pauseAt(new Date());
  await page.goto('/');
  await page.getByRole('checkbox', { name: 'Teaching mode', exact: true }).check();
  await page.getByRole('button', { name: 'Start expedition' }).click();
  await page.clock.runFor(100);
  await expect(page.getByLabel('Decision phase', { exact: true })).toHaveText('Teaching pause');
  await expect(page.getByLabel('Current action', { exact: true })).toHaveText('Choice held before execution');
  await expect(page.getByRole('region', { name: 'Latest decision' })).toContainText('#1 · 00:00');
  const marker = page.getByRole('button', { name: /Inspect decision 1 target .*Selected/ }).first();
  await expect(marker).toBeAttached();
  await marker.click();
  await expect(page.getByLabel('Decision 1 details')).toBeVisible();
  await closePanel(page);
  await page.clock.fastForward(60_000);
  await expect(page.getByLabel('Remaining expedition time')).toHaveText('18:00');
  await page.getByRole('button', { name: 'Continue selected action', exact: true }).click();
  await page.clock.fastForward(30_000);
  await expect(page.getByLabel('Decision phase', { exact: true })).toHaveText('Teaching pause');
  const time = await page.getByLabel('Remaining expedition time').textContent();
  const history = page.getByRole('button', { name: /^Inspect decision 1 at/ });
  await history.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByLabel('Decision phase', { exact: true })).toHaveText('Manual inspection');
  await expect(page.getByRole('region', { name: 'Latest decision' })).toContainText('Historical decision selected');
  await expect(page.getByLabel('Decision map context')).toContainText('Decision 1 · 00:00');
  await expect(page.getByLabel('Decision 1 details')).toContainText('Battery 160.0 / 160');
  await expect(page.getByRole('checkbox', { name: 'Full-world debugging view' })).toBeDisabled();
  await page.getByRole('button', { name: 'Follow rover', exact: true }).click();
  await page.clock.fastForward(60_000);
  await expect(page.getByLabel('Remaining expedition time')).toHaveText(time!);
  await page.screenshot({ path: 'test-results/decision-history-desktop.png' });
  await page.keyboard.press('Escape');
  await expect(page.getByLabel('Decision phase', { exact: true })).toHaveText('Teaching pause');
  await page.getByRole('button', { name: 'Continue selected action', exact: true }).click();
  await page.clock.runFor(100);
  await expect(page.getByLabel('Decision phase', { exact: true })).toHaveText('Code executing');
});

test('a saved teaching expedition replays one choice at a time without new inference', async ({ page }) => {
  await page.clock.install();
  await page.clock.pauseAt(new Date());
  await page.goto('/');
  await page.getByRole('checkbox', { name: 'Teaching mode', exact: true }).check();
  await page.getByRole('button', { name: 'Start expedition' }).click();
  await page.getByRole('button', { name: 'Continue selected action' }).click();
  await page.clock.fastForward(30_000);
  await page.getByRole('button', { name: 'Stop expedition' }).click();
  await openPanel(page, 'Saved expeditions');
  await page.getByRole('button', { name: /Open expedition/ }).click();
  let calls = 0;
  await page.route('**/api/**', route => { calls++; return route.abort(); });
  await page.getByRole('button', { name: 'Replay expedition', exact: true }).click();
  const replay = page.getByRole('region', { name: 'Expedition replay' });
  await replay.getByRole('checkbox', { name: 'Replay teaching mode' }).check();
  await replay.getByRole('button', { name: 'Restart replay' }).click();
  await expect(replay.getByRole('button', { name: 'Continue recorded action' })).toBeVisible();
  await page.clock.fastForward(60_000);
  await expect(replay.getByLabel('Replay elapsed time')).toHaveText('00:00');
  await replay.getByRole('button', { name: 'Continue recorded action' }).click();
  await page.clock.fastForward(60_000);
  await expect(replay.getByRole('button', { name: 'Continue recorded action' })).toBeVisible();
  await expect(replay.getByLabel('Replay elapsed time')).toHaveText('00:04');
  await replay.getByRole('button', { name: 'Continue recorded action' }).click();
  await expect(replay.getByRole('status')).toHaveText('Replay complete');
  expect(calls).toBe(0);
});

test('a pending Jev response settles during inspection without resuming, and its wait target is linked to evidence', async ({ page, request }) => {
  await page.clock.install();
  await page.clock.pauseAt(new Date());
  let submissions = 0;
  page.on('request', request => { if (request.url().endsWith('/api/decision')) submissions++; });
  await page.goto('/');
  await openPanel(page, 'Mission');
  await page.getByRole('combobox', { name: 'Expedition controller' }).selectOption('typesafe');
  await page.getByRole('button', { name: 'Start expedition' }).click();
  const card = page.getByRole('region', { name: 'Latest decision' });
  await expect(card).toContainText('Wait · 5 seconds');
  await openPanel(page, 'Mission');
  await page.getByRole('textbox', { name: 'Mission instructions' }).fill('Hold for browser verification');
  await page.getByRole('button', { name: 'Apply instructions' }).click();
  await closePanel(page);
  await page.clock.fastForward(5000);
  await expect(card).toContainText('Previous completed choice · History');
  await page.getByRole('button', { name: /^Inspect decision 1 at/ }).click();
  await request.post('http://127.0.0.1:4174/release');
  await expect(page.getByLabel('Current action', { exact: true })).toHaveText('Choice held before execution');
  await expect(page.getByLabel('Decision phase', { exact: true })).toHaveText('Manual inspection');
  await page.clock.runFor(100);
  await expect(page.getByRole('button', { name: /Inspect decision 1 target .*Selected wait · Rover/ })).toBeAttached();
  await expect(page.getByRole('table', { name: 'Available actions' })).toContainText('Returned probability');
  await expect(page.getByLabel('Decision 1 details')).toContainText('$0.00004200 USD');
  await page.clock.fastForward(60_000);
  await expect(page.getByLabel('Remaining expedition time')).toHaveText('17:55');
  expect(submissions).toBe(2);
  await closePanel(page);
  await page.getByRole('button', { name: 'Resume expedition' }).click();
  await page.clock.runFor(100);
  await expect(page.getByLabel('Current action', { exact: true })).toContainText('Wait');
  expect(submissions).toBe(2);
});

