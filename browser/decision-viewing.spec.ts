test('legacy recharge targets and unavailable evidence remain inspectable and export unchanged without inference', async ({ page }) => {
  const source = await readFile('tests/fixtures/legacy-cadence-v6.json', 'utf8');
  const record = JSON.parse(source);
  const recharge = record.decisions.find((item: { action?: { kind: string } }) => item.action?.kind === 'recharge');
  expect(recharge).toBeTruthy();
  let calls = 0;
  await page.route('**/api/**', route => { calls++; return route.abort(); });
  await page.clock.install();
  await page.clock.pauseAt(new Date());
  await page.goto('/');
  await openPanel(page, 'Saved expeditions');
  await page.getByLabel('Import expedition JSON').setInputFiles({ name: 'legacy.json', mimeType: 'application/json', buffer: Buffer.from(source) });
  const saved = page.getByRole('region', { name: 'Saved expedition', exact: true });
  await saved.locator('summary').filter({ hasText: `Decision ${recharge.id} ·` }).click();
  await page.clock.runFor(100);
  await expect(saved.getByRole('button', { name: new RegExp(`Inspect decision ${recharge.id} target .*Selected recharge · Base`) })).toBeAttached();
  await expect(saved.getByRole('table', { name: 'Available actions' })).toContainText('Unavailable');
  const download = page.waitForEvent('download');
  await saved.getByRole('button', { name: 'Export expedition JSON' }).click();
  expect(JSON.parse(await readFile((await (await download).path())!, 'utf8'))).toEqual(record);
  expect(calls).toBe(0);
});
