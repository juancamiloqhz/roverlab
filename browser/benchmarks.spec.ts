import { expect, test } from '@playwright/test';
import { openPanel, closePanel } from './panels';

test('choose, inspect, run, and compare a benchmark in layout A without provider access', async ({ page }) => {
  test.setTimeout(120_000);
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') });
  await page.clock.pauseAt(new Date('2026-01-01T00:00:01Z'));
  let requests = 0;
  await page.route('**/api/**', route => { requests++; return route.abort(); });
  await page.goto('/');
  await openPanel(page, 'Mission');
  await page.getByRole('combobox', { name: 'Benchmark scenario' }).selectOption('evidence-survey');
  const benchmark = page.getByRole('region', { name: 'Benchmark scenario' });
  await expect(benchmark).toContainText('Inspect clear and ambiguous evidence');
  await expect(benchmark).toContainText('160');
  await expect(benchmark).toContainText('12 sites');
  await expect(page.getByRole('combobox', { name: 'Scientific objective' })).toHaveValue('past-water');
  await expect(page.getByRole('region', { name: 'Intervention schedule', exact: true }).first()).toContainText('No interventions');
  await page.clock.runFor(100);
  await page.screenshot({ path: 'test-results/benchmark-conditions-desktop.png' });
  await page.getByRole('button', { name: 'Start expedition' }).click();
  await openPanel(page, 'Mission');
  await expect(page.getByRole('combobox', { name: 'Benchmark scenario' })).toBeDisabled();
  await closePanel(page);
  await page.clock.fastForward(1_080_000);
  await expect(page.getByLabel('Science score')).toHaveText('10');
  await openPanel(page, 'Saved expeditions');
  await page.getByRole('button', { name: /Open expedition/ }).click();
  const saved = page.getByRole('region', { name: 'Saved expedition', exact: true });
  await expect(saved).toContainText('Evidence survey v1');
  await page.getByRole('button', { name: 'Run matched baseline', exact: true }).click();
  await page.clock.fastForward(1_080_000);
  await page.getByRole('button', { name: 'Compare with source expedition' }).click();
  const comparison = page.getByRole('region', { name: 'Expedition comparison', exact: true });
  await expect(comparison.getByRole('status')).toContainText('Matching external conditions');
  await expect(comparison.getByRole('row', { name: /^Selected benchmark/ })).toContainText('Evidence survey v1');
  await expect(comparison.getByRole('row', { name: /^Science score/ })).toContainText('10');
  expect(requests).toBe(0);
});

test('inspect a storm benchmark on a narrow screen and keep world controls usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.clock.install();
  await page.goto('/');
  await openPanel(page, 'Mission');
  await page.getByRole('combobox', { name: 'Benchmark scenario' }).selectOption('storm-response');
  await expect(page.getByRole('region', { name: 'Benchmark scenario' })).toContainText('three-minute storm');
  await expect(page.getByRole('combobox', { name: 'Scientific objective' })).toHaveValue('unusual-minerals');
  await page.getByText('01:00.0 · Dust storm', { exact: true }).scrollIntoViewIfNeeded();
  await expect(page.getByText('Center 26 / 24', { exact: false })).toBeVisible();
  await page.screenshot({ path: 'test-results/benchmark-schedule-narrow.png' });
  await closePanel(page);
  await page.getByRole('button', { name: 'Follow rover', exact: true }).click();
  await page.getByRole('button', { name: 'Start expedition' }).click();
  await page.clock.fastForward(65_000);
  await page.getByRole('button', { name: 'Pause expedition' }).click();
  const remaining = await page.getByLabel('Remaining expedition time').textContent();
  await page.getByRole('button', { name: 'Orbit camera', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Full-world debugging view' }).check();
  await page.clock.runFor(100);
  await expect(page.getByLabel('Remaining expedition time')).toHaveText(remaining!);
  await page.screenshot({ path: 'test-results/benchmark-world-narrow.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Reset expedition' }).click();
  await openPanel(page, 'Mission');
  await expect(page.getByRole('combobox', { name: 'Benchmark scenario' })).toHaveValue('storm-response');
  await page.getByRole('combobox', { name: 'Benchmark scenario' }).selectOption('changing-priorities');
  await expect(page.getByRole('region', { name: 'Benchmark scenario' })).toContainText('Conserve energy at 06:00');
  await page.getByRole('combobox', { name: 'Benchmark scenario' }).selectOption('');
  await expect(page.getByRole('combobox', { name: 'Benchmark scenario' })).toHaveValue('');
});
